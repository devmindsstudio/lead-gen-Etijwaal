// Generates the site registry and domain map from /sites/*.json, so adding a site
// is just "drop a JSON file in /sites". Runs automatically before dev and build.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Z]:)/, "$1");
const dir = join(root, "sites");
const files = readdirSync(dir).filter((f) => f.endsWith(".json")).sort();

const ident = (id) => id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()).replace(/^(\d)/, "_$1");
const header = "// GENERATED by scripts/sync-sites.mjs from /sites/*.json. Do not edit.\n";

const sites = files.map((f) => JSON.parse(readFileSync(join(dir, f), "utf8")));

writeFileSync(
  join(root, "src/lib/sites.generated.ts"),
  header +
    files.map((f, i) => `import ${ident(sites[i].id)} from "../../sites/${f}";`).join("\n") +
    `\n\nexport const rawSites: unknown[] = [${sites.map((s) => ident(s.id)).join(", ")}];\n`,
);

const hosts = {};
for (const s of sites) {
  hosts[s.domain] = { site: s.id, canonical: true };
  for (const a of s.aliases ?? []) hosts[a] = { site: s.id, canonical: false };
}
writeFileSync(
  join(root, "src/lib/hosts.generated.ts"),
  header +
    `export const hosts: Record<string, { site: string; canonical: boolean }> = ${JSON.stringify(hosts, null, 2)};\n`,
);

console.log(`  synced ${sites.length} site(s): ${sites.map((s) => s.domain).join(", ")}`);
